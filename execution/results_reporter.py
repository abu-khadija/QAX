"""
results_reporter.py — Test Execution Results Reporter
======================================================
Transforms raw batch execution results into human-readable and
machine-readable formats, and optionally uploads to Xray.

Three output channels:
  1. Console summary  — Prints a colour-coded table to stdout
  2. HTML report      — Self-contained HTML file with pass/fail details
  3. Xray upload      — POSTs results to Xray Cloud test execution API

DRY_RUN guard:
  report_to_xray() ALWAYS checks DRY_RUN before making any API call.
  If DRY_RUN=true (or not set), it logs what it would upload and returns
  a mock result — zero real API calls are made.

All methods are synchronous except report_to_xray which is async to
match the XrayClient interface. All methods are wrapped in try/except
and never raise — they return safe defaults on any error.
"""

