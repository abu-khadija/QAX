class ResultsReporter:
    """
    Formats and publishes test execution results.

    Provides three output methods:
      - generate_console_summary() — prints a quick pass/fail table
      - generate_html_report()     — saves a self-contained HTML report
      - report_to_xray()           — uploads to Xray (honours DRY_RUN)

    Usage:
        reporter = ResultsReporter()
        reporter.generate_console_summary(batch_results)
        html_path = reporter.generate_html_report(batch_results, "output/reports")
        upload_result = await reporter.report_to_xray(batch_results, xray_client)
    """

    def __init__(self) -> None:
        """
        Initialize the reporter.

        Reads DRY_RUN from the environment at construction time. This
        value controls whether report_to_xray makes real API calls.
        """
        self._dry_run = os.getenv("DRY_RUN", "true").lower() == "true"

    # ─────────────────────────────────────────────────────────────────────────
    # Public: generate_console_summary
    # ─────────────────────────────────────────────────────────────────────────

    def generate_console_summary(self, batch_results: dict) -> None:
        """
        Print a formatted pass/fail summary table to stdout.

        Shows an overview of the batch (pass rate, counts), then a
        per-test-case row with ID, title, status, duration, and whether
        any steps were AI-healed.

        Args:
            batch_results (dict): Batch result dict from
                                   TestExecutor.execute_batch(). Expected keys:
                                   - total, passed, failed, errors, skipped
                                   - pass_rate, duration_seconds
                                   - results (list of test case result dicts)

        Returns:
            None. Prints to stdout. Never raises.
        """
        try:
            total    = batch_results.get("total", 0)
            passed   = batch_results.get("passed", 0)
            failed   = batch_results.get("failed", 0)
            errors   = batch_results.get("errors", 0)
            skipped  = batch_results.get("skipped", 0)
            rate     = batch_results.get("pass_rate", 0.0)
            duration = batch_results.get("duration_seconds", 0.0)
            results  = batch_results.get("results", [])

            print("\n" + "=" * 65)
            print("  QAX — EXECUTION RESULTS")
            print("=" * 65)
            print(f"  Tests   : {total}  |  Pass: {passed}  Fail: {failed}  "
                  f"Error: {errors}  Skip: {skipped}")
            print(f"  Rate    : {rate:.1f}%  |  Duration: {duration:.1f}s")
            if batch_results.get("stopped_early"):
                print("  NOTE    : Execution stopped early (stop_on_fail=True)")
            print("-" * 65)

            if not results:
                print("  No results to display.")
            else:
                # ── Per test case ──────────────────────────────────────────
                for r in results:
                    tc_id  = r.get("test_case_id", "?")
                    title  = r.get("title", "Untitled")[:40]
                    status = r.get("status", "?")
                    dur    = r.get("duration_seconds", 0.0)
                    healed = r.get("healed_steps", 0)

                    status_icon = {
                        "PASS":  "✓",
                        "FAIL":  "✗",
                        "ERROR": "!",
                        "SKIP":  "-",
                    }.get(status, "?")

                    heal_tag = f" [+{healed} healed]" if healed else ""
                    print(
                        f"  {status_icon} [{status:<5}] {tc_id:<18} {title:<40} "
                        f"{dur:>5.1f}s{heal_tag}"
                    )

                    # ── Show step failures inline ──────────────────────────
                    for step in r.get("steps", []):
                        if step.get("status") in ("FAIL", "ERROR"):
                            err = step.get("error", "")[:70]
                            snum = step.get("step_number", "?")
                            print(f"      ✗ Step {snum}: {err}")

                    if r.get("error"):
                        print(f"      ✗ Error: {r['error'][:80]}")

            print("=" * 65 + "\n")

        except Exception as e:  # noqa: BLE001
            logger.error("generate_console_summary error: %s", e)

    # ─────────────────────────────────────────────────────────────────────────
    # Public: generate_html_report
    # ─────────────────────────────────────────────────────────────────────────

    def generate_html_report(
        self,
        batch_results: dict,
        output_folder: str = "output/reports",
    ) -> str:
        """
        Generate a self-contained HTML execution report and save it to disk.

        The report includes:
          - Summary cards (total / pass / fail / error / pass rate)
          - A per-test-case table with expandable step details
          - Failure screenshots listed (paths, not embedded)

        Args:
            batch_results (dict): Batch result from TestExecutor.execute_batch().
            output_folder (str): Folder to save the HTML file in.
                                  Default: "output/reports". Created if absent.

        Returns:
            str: Absolute path to the saved HTML file.
                 Empty string if any error occurs.
        """
        try:
            Path(output_folder).mkdir(parents=True, exist_ok=True)
            timestamp = datetime.now(timezone.utc).strftime("%Y%m%d_%H%M%S")
            file_path = str(Path(output_folder) / f"execution_report_{timestamp}.html")

            html = self._build_html(batch_results)

            with open(file_path, "w", encoding="utf-8") as f:
                f.write(html)

            logger.info("HTML report saved: %s", file_path)
            return file_path

        except Exception as e:  # noqa: BLE001
            logger.error("generate_html_report error: %s", e)
            return ""

    # ─────────────────────────────────────────────────────────────────────────
    # Public: report_to_xray
    # ─────────────────────────────────────────────────────────────────────────

    async def report_to_xray(
        self,
        batch_results: dict,
        xray_client,
    ) -> dict:
        """
        Upload execution results to Xray Cloud via XrayClient.

        IMPORTANT: Checks DRY_RUN before every API call. If DRY_RUN=true,
        this method logs what it would upload and returns a mock result
        without making any real API calls.

        For each test case result with status PASS or FAIL:
          - Calls xray_client.update_test_execution(test_case_id, status, comment)

        Args:
            batch_results (dict): Batch result from TestExecutor.execute_batch().
            xray_client: Initialized XrayClient instance.

        Returns:
            dict: Upload summary with keys:
                    - dry_run (bool): Whether DRY_RUN was active
                    - attempted (int): Number of results attempted
                    - uploaded (int): Number successfully uploaded
                    - failed (int): Number that failed to upload
                    - skipped (int): Number skipped (no xray_client, status=SKIP)
                    - details (list[dict]): Per-result upload status
        """
        results = batch_results.get("results", [])
        summary = {
            "dry_run": self._dry_run,
            "attempted": 0,
            "uploaded": 0,
            "failed": 0,
            "skipped": 0,
            "details": [],
        }

        if not xray_client:
            logger.warning("report_to_xray: no xray_client provided — skipping upload")
            summary["skipped"] = len(results)
            return summary

        for r in results:
            tc_id  = r.get("test_case_id", "")
            status = r.get("status", "SKIP")
            title  = r.get("title", "")
            healed = r.get("healed_steps", 0)

            # ── Skip non-reportable statuses ───────────────────────────────
            if status in ("SKIP", "ERROR") or not tc_id:
                summary["skipped"] += 1
                summary["details"].append({"test_case_id": tc_id, "upload_status": "SKIPPED"})
                continue

            summary["attempted"] += 1

            # ── Build comment ──────────────────────────────────────────────
            comment_lines = [f"Automated execution result: {status}"]
            if healed:
                comment_lines.append(f"  AI-healed steps: {healed}")
            if r.get("error"):
                comment_lines.append(f"  Error: {r['error'][:200]}")
            if r.get("screenshot"):
                comment_lines.append(f"  Screenshot: {r['screenshot']}")
            comment_lines.append(f"  Duration: {r.get('duration_seconds', 0):.1f}s")
            comment = "\n".join(comment_lines)

            # ── DRY_RUN guard ──────────────────────────────────────────────
            if self._dry_run:
                logger.info(
                    "[DRY_RUN] Would upload to Xray: %s → %s", tc_id, status
                )
                summary["uploaded"] += 1
                summary["details"].append({
                    "test_case_id": tc_id,
                    "upload_status": "DRY_RUN",
                    "xray_status": status,
                })
                continue

            # ── Real upload ────────────────────────────────────────────────
            try:
                ok = xray_client.update_test_execution(tc_id, status, comment)
                if ok:
                    summary["uploaded"] += 1
                    summary["details"].append({
                        "test_case_id": tc_id,
                        "upload_status": "OK",
                        "xray_status": status,
                    })
                    logger.info("Uploaded to Xray: %s → %s", tc_id, status)
                else:
                    summary["failed"] += 1
                    summary["details"].append({
                        "test_case_id": tc_id,
                        "upload_status": "FAILED",
                    })
                    logger.warning("Xray upload failed for %s", tc_id)

            except Exception as e:  # noqa: BLE001
                logger.error("report_to_xray error for %s: %s", tc_id, e)
                summary["failed"] += 1
                summary["details"].append({
                    "test_case_id": tc_id,
                    "upload_status": "ERROR",
                    "error": str(e)[:100],
                })

        logger.info(
            "Xray upload complete: %d uploaded, %d failed, %d skipped (dry_run=%s)",
            summary["uploaded"], summary["failed"], summary["skipped"], self._dry_run
        )

        # ── Severity upgrade: promote critical failures ─────────────────────
        # After all tests are uploaded, re-check any failed tests with
        # risk_level=critical and a bug_key. If found, call update_severity()
        # to ensure the Jira severity field is set to "Critical" as a real
        # field value — not just text in the description.
        self._upgrade_critical_severities(results)

        return summary

    def _upgrade_critical_severities(self, results: list[dict]) -> None:
        """
        Upgrade the Jira severity field to "Critical" for any failed test
        that has risk_level=critical and an associated bug_key.

        Called automatically at the end of report_to_xray() after all
        results have been uploaded. This ensures severity is always correct
        as a real Jira field value even when the initial bug creation used a
        lower severity due to confidence-based mapping.

        Args:
            results (list[dict]): List of test case result dicts from
                                   TestExecutor.execute_batch().

        Returns:
            None. Logs outcomes. Never raises.
        """
        critical_bugs = [
            r for r in results
            if (
                r.get("risk_level", "").lower() == "critical"
                and r.get("bug_key")
                and r.get("status") in ("FAIL", "ERROR")
            )
        ]

        if not critical_bugs:
            return

        try:
            from core.bug_reporter import BugReporter
            reporter = BugReporter()

            for r in critical_bugs:
                bug_key = r["bug_key"]
                ok = reporter.update_severity(bug_key, "Critical")
                if ok:
                    logger.info(
                        "Severity upgraded to Critical: %s", bug_key
                    )
                else:
                    logger.warning(
                        "Severity upgrade failed for: %s", bug_key
                    )
        except Exception as e:  # noqa: BLE001
            logger.debug("_upgrade_critical_severities error (non-fatal): %s", e)

    # ─────────────────────────────────────────────────────────────────────────
    # Private: _build_html
    # ─────────────────────────────────────────────────────────────────────────

    def _build_html(self, batch_results: dict) -> str:
        """
        Build the complete HTML string for the execution report.

        Args:
            batch_results (dict): Batch result dict from execute_batch().

        Returns:
            str: Full HTML document as a string.
        """
        total    = batch_results.get("total", 0)
        passed   = batch_results.get("passed", 0)
        failed   = batch_results.get("failed", 0)
        errors   = batch_results.get("errors", 0)
        skipped  = batch_results.get("skipped", 0)
        rate     = batch_results.get("pass_rate", 0.0)
        duration = batch_results.get("duration_seconds", 0.0)
        results  = batch_results.get("results", [])
        now_str  = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC")

        html = _HTML_HEAD.format(generated_at=now_str, duration=f"{duration:.1f}")

        # ── Summary cards ──────────────────────────────────────────────────
        html += '<div class="summary">\n'
        cards = [
            (total,   "Total",   ""),
            (passed,  "Passed",  "pass"),
            (failed,  "Failed",  "fail"),
            (errors,  "Errors",  "error"),
            (skipped, "Skipped", "skip"),
            (f"{rate:.1f}%", "Pass Rate", "pass" if rate >= 90 else ("fail" if rate < 70 else "")),
        ]
        for val, label, cls in cards:
            html += (
                f'  <div class="card"><div class="num {cls}">{val}</div>'
                f'<div class="lbl">{label}</div></div>\n'
            )
        html += '</div>\n'

        # ── Results table ──────────────────────────────────────────────────
        if not results:
            html += "<p>No results to display.</p>\n"
        else:
            html += (
                '<table>\n'
                '<tr><th>Test Case</th><th>Title</th><th>Status</th>'
                '<th>Duration</th><th>Healed</th><th>Steps / Errors</th></tr>\n'
            )
            for r in results:
                tc_id  = r.get("test_case_id", "?")
                title  = r.get("title", "Untitled")
                status = r.get("status", "?")
                dur    = r.get("duration_seconds", 0.0)
                healed = r.get("healed_steps", 0)
                badge_cls = {
                    "PASS": "b-pass", "FAIL": "b-fail",
                    "ERROR": "b-error", "SKIP": "b-skip",
                    "HEALED": "b-heal",
                }.get(status, "")

                # ── Inline step details ────────────────────────────────────
                step_html = ""
                failed_steps = [
                    s for s in r.get("steps", [])
                    if s.get("status") in ("FAIL", "ERROR")
                ]
                if failed_steps:
                    step_html = "<details><summary>View failures</summary><ul>"
                    for s in failed_steps:
                        step_html += (
                            f"<li>Step {s.get('step_number','?')}: "
                            f"{self._escape(s.get('error','')[:120])}</li>"
                        )
                    step_html += "</ul></details>"
                elif r.get("error"):
                    step_html = self._escape(r["error"][:120])

                if r.get("screenshot"):
                    step_html += f'<br><small>Screenshot: {self._escape(r["screenshot"])}</small>'

                html += (
                    f"<tr>"
                    f"<td><code>{self._escape(tc_id)}</code></td>"
                    f"<td>{self._escape(title)}</td>"
                    f'<td><span class="badge {badge_cls}">{status}</span></td>'
                    f"<td>{dur:.1f}s</td>"
                    f"<td>{'✓' if healed else ''}{healed or ''}</td>"
                    f"<td>{step_html}</td>"
                    f"</tr>\n"
                )
            html += "</table>\n"

        html += _HTML_FOOT.format(dry_run=str(self._dry_run))
        return html

    def _escape(self, text: str) -> str:
        """
        HTML-escape a string for safe inclusion in HTML content.

        Args:
            text (str): Raw string to escape.

        Returns:
            str: HTML-safe string.
        """
        return (
            str(text)
            .replace("&", "&amp;")
            .replace("<", "&lt;")
            .replace(">", "&gt;")
            .replace('"', "&quot;")
        )
