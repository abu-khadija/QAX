"""
markdown_reporter.py — PR Comment Generator
=============================================
Generates Markdown-formatted PR/MR comment strings from a list of
generated test cases, suitable for posting on GitHub Pull Requests
or GitLab Merge Requests by the CI/CD pipeline.

The generated comment shows:
  - How many test cases were found, across how many files
  - A table of all test cases: title, module, type, confidence
  - A footer linking to the project

Usage:
    from core.markdown_reporter import generate_pr_comment

    comment = generate_pr_comment(test_cases, changed_files)
    # comment is a plain string ready to POST to a PR/MR API

Also callable from main.py analyze:
    python main.py analyze --file src/Orders/OrderController.cs \
                           --output pr_comment.md
    # Saves the comment as a .md file instead of JSON
"""

import logging
from datetime import datetime, timezone
from pathlib import Path

logger = logging.getLogger(__name__)

# ── Maximum rows to include in the table (keeps the comment readable) ─────────
MAX_TABLE_ROWS = 30


def generate_pr_comment(
    test_cases: list,
    changed_files: list,
) -> str:
    """
    Build a Markdown PR comment summarising the generated test cases.

    Produces a comment in this format:

      ## Robot QAX — Generated Tests

      Found **X test cases** for **Y changed files**.

      | Test Case | Module | Type | Confidence |
      |-----------|--------|------|------------|
      | Title...  | mod    | type | 8/10       |

      > Review these test cases and merge to push to Xray.

      *Generated by QAX — DRY_RUN=true*

    Handles empty test_cases gracefully (returns a "no tests found" message).
    Never raises — returns a minimal fallback string on any error.

    Args:
        test_cases (list): List of test case dicts from Claude. Each should
                            have keys: title, module, test_type,
                            confidence_score, test_case_id.
        changed_files (list): List of file path strings that were changed in
                               the PR (used for the summary line).

    Returns:
        str: A complete Markdown string ready to post as a PR comment.
    """
    try:
        return _build_comment(test_cases, changed_files)
    except Exception as e:  # noqa: BLE001
        logger.error("generate_pr_comment error: %s", e)
        return (
            "## QAX\n\n"
            f"Error generating test case report: {e}\n\n"
            "*Please check the CI logs for details.*\n"
        )


def _build_comment(test_cases: list, changed_files: list) -> str:
    """
    Internal builder for the PR comment markdown string.

    Args:
        test_cases (list): Test case dicts.
        changed_files (list): Changed file paths.

    Returns:
        str: Formatted Markdown comment.
    """
    n_cases = len(test_cases) if test_cases else 0
    n_files = len(changed_files) if changed_files else 0

    ts = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    lines = []

    # ── Header ────────────────────────────────────────────────────────────
    lines.append("## \U0001f916 QAX \u2014 Generated Tests")
    lines.append("")

    # ── No tests found ────────────────────────────────────────────────────
    if n_cases == 0:
        lines.append(
            f"No test cases were generated for the **{n_files}** changed file(s) in this PR."
        )
        lines.append("")
        if changed_files:
            lines.append("**Changed files:**")
            for f in changed_files[:10]:
                lines.append(f"- `{Path(f).name}`")
            if n_files > 10:
                lines.append(f"- *…and {n_files - 10} more*")
            lines.append("")
        lines.append(
            "> **Note:** Files may have been skipped because they contained no testable logic, "
            "or Claude API credentials were not configured."
        )
        lines.append("")
        lines.append(f"*Generated by QAX \u2014 {ts}*")
        return "\n".join(lines)

    # ── Summary line ──────────────────────────────────────────────────────
    files_label = f"**{n_files} changed file{'s' if n_files != 1 else ''}**"
    cases_label = f"**{n_cases} test case{'s' if n_cases != 1 else ''}**"
    lines.append(f"Found {cases_label} for {files_label}.")
    lines.append("")

    # ── Changed files list (collapsed if many) ────────────────────────────
    if changed_files:
        if n_files <= 5:
            lines.append("**Changed files analyzed:**")
            for f in changed_files:
                lines.append(f"- `{Path(f).name}`")
        else:
            lines.append(
                f"<details><summary><strong>Changed files analyzed ({n_files})</strong></summary>"
            )
            lines.append("")
            for f in changed_files:
                lines.append(f"- `{f}`")
            lines.append("</details>")
        lines.append("")

    # ── Test cases table ──────────────────────────────────────────────────
    table_rows = test_cases[:MAX_TABLE_ROWS]
    remaining  = n_cases - len(table_rows)

    lines.append("| Test Case | Module | Type | Steps | Confidence |")
    lines.append("|-----------|--------|------|-------|------------|")

    for tc in table_rows:
        title      = _escape_md(str(tc.get("title", "Untitled"))[:70])
        module     = _escape_md(str(tc.get("module", "\u2014")))
        test_type  = _escape_md(str(tc.get("test_type", tc.get("type", "\u2014"))))
        confidence = tc.get("confidence_score", "?")
        n_steps    = len(tc.get("steps", []))
        conf_disp  = f"{confidence}/10" if isinstance(confidence, int) else str(confidence)
        lines.append(f"| {title} | {module} | {test_type} | {n_steps} | {conf_disp} |")

    if remaining > 0:
        lines.append(f"| *…and {remaining} more test cases* | | | | |")

    lines.append("")

    # ── Module summary (if multiple modules) ──────────────────────────────
    modules: dict[str, int] = {}
    for tc in test_cases:
        mod = tc.get("module", "")
        if mod:
            modules[mod] = modules.get(mod, 0) + 1

    if len(modules) > 1:
        lines.append("**By module:**")
        for mod, count in sorted(modules.items(), key=lambda x: -x[1]):
            lines.append(f"- **{mod}**: {count} test case{'s' if count != 1 else ''}")
        lines.append("")

    # ── Confidence summary ────────────────────────────────────────────────
    scores = [
        tc.get("confidence_score")
        for tc in test_cases
        if isinstance(tc.get("confidence_score"), (int, float))
    ]
    if scores:
        avg_score = round(sum(scores) / len(scores), 1)
        high_conf = sum(1 for s in scores if s >= 8)
        lines.append(
            f"> **Quality:** Average confidence {avg_score}/10 \u2014 "
            f"{high_conf}/{len(scores)} cases scored 8+/10"
        )
        lines.append("")

    # ── Call to action ────────────────────────────────────────────────────
    lines.append(
        "> **Next step:** Review the test cases above and run "
        "`python main.py run --mode generate` to push them to Xray."
    )
    lines.append("")
    lines.append(
        f"*Generated by [QAX](https://github.com) \u2014 "
        f"DRY\\_RUN=true \u2014 {ts}*"
    )

    return "\n".join(lines)


def _escape_md(text: str) -> str:
    """
    Escape Markdown table cell characters to prevent broken table formatting.

    Replaces pipe characters (which would break the table column delimiter)
    and trims whitespace.

    Args:
        text (str): Raw text to escape.

    Returns:
        str: Safe text for use inside a Markdown table cell.
    """
    return str(text).replace("|", "\\|").replace("\n", " ").strip()
